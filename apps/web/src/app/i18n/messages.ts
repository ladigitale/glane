export type MessageKey = keyof typeof fr;

export const MESSAGES: Record<AppLocale, WordingCatalog> = {
  fr,
  en,
};

export function resolveWordings(
  labels: string[],
  locale: AppLocale,
): Record<string, string> {
  const catalog = MESSAGES[locale] ?? MESSAGES.fr;
  const fallback = MESSAGES.fr;
  const result: Record<string, string> = {};
  for (const key of labels) {
    if (!key) continue;
    result[key] = catalog[key] ?? fallback[key] ?? key;
  }
  return result;
}

/** Sync lookup for non-Lit strings (dialogs, errors) and existing `t()` call sites. */
export function tx(key: string, locale: AppLocale = getAppLocale()): string {
  return MESSAGES[locale]?.[key] ?? MESSAGES.fr[key] ?? key;
}

/** Sync lookup with `{name}` / `{n}` interpolation. */
export function tf(
  key: string,
  vars: Record<string, string | number>,
  locale?: AppLocale,
): string {
  let text = tx(key, locale);
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

/** Persist + apply locale (Concorde `html[lang]` + Sonic storage). */
export function setLocale(l: Locale): void {
  setAppLocale(l);
}

/** Typed sync wording (Glane call sites). Prefer Concorde `t()` in new Lit templates. */
export function t(key: MessageKey): string {
  return tx(key);
}
